"""Deterministic JPEG copies of existing product art for email clients without WebP support.
Same pictures, resized to 480px; no artwork changes. Re-run after adding product images."""
import glob, os, json
from PIL import Image
src = sorted(glob.glob("public/images/product-optimized/*.webp")) + sorted(glob.glob("public/images/titan-*.webp"))
src = [p for p in src if not p.endswith(("-480.webp", "-960.webp"))]
out = {}
for p in src:
    rel = "/" + os.path.relpath(p, "public")
    name = rel.strip("/").replace("images/", "").replace("/", "__").replace(".webp", ".jpg")
    im = Image.open(p).convert("RGB")
    im.thumbnail((480, 480), Image.LANCZOS)
    im.save(f"public/images/email/{name}", "JPEG", quality=85, optimize=True, progressive=False)
    out[rel] = f"/images/email/{name}"
with open("src/lib/email-image-map.ts", "w") as f:
    f.write("// Generated by scripts/build-email-images.py — do not edit.\nexport const EMAIL_IMAGE_MAP: Record<string, string> = " + json.dumps(out, indent=2) + ";\n")
print(len(out))
